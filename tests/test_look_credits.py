"""A Look's credits: the notice its assets' licence asks to travel with a
video, appended to the YouTube description of every export drawn with it."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

from splitsmith import looks, youtube_sidecar
from splitsmith.looks import look_credits


def _user_look(tmp_path: Path, *, credits: str | None, text: str | None = None) -> Path:
    """A copy of the shipped splitsmith Look under a user name, with
    ``credits`` set in its manifest and ``text`` in that file."""
    root = tmp_path / "looks" / "mine"
    shutil.copytree(looks.shipped_looks_dir() / "splitsmith", root)
    manifest = json.loads((root / "look.json").read_text())
    manifest["name"] = "mine"
    if credits is not None:
        manifest["credits"] = credits
    (root / "look.json").write_text(json.dumps(manifest))
    if text is not None and credits is not None:
        (root / credits).write_text(text, encoding="utf-8")
    return root


@pytest.fixture
def user_looks(tmp_path: Path):
    token = looks.set_user_looks_provider(lambda: tmp_path / "looks")
    yield tmp_path
    looks.reset_user_looks_provider(token)


def test_a_look_names_its_credits_file(user_looks: Path) -> None:
    _user_look(user_looks, credits="CREDITS.txt", text="Art from Somewhere.\n\nBSD licence.\n")
    assert look_credits(looks.load_look("mine")) == "Art from Somewhere.\n\nBSD licence."


def test_a_look_without_credits_has_none(user_looks: Path) -> None:
    _user_look(user_looks, credits=None)
    assert look_credits(looks.load_look("mine")) is None
    assert look_credits(looks.load_look("splitsmith")) is None


@pytest.mark.parametrize("name", ["../outside.txt", "missing.txt"])
def test_credits_outside_the_look_or_missing_are_none(user_looks: Path, name: str) -> None:
    (user_looks / "looks" / "outside.txt").parent.mkdir(parents=True, exist_ok=True)
    _user_look(user_looks, credits=name)
    (user_looks / "looks" / "outside.txt").write_text("secret")
    assert look_credits(looks.load_look("mine")) is None


def test_credits_close_the_description_in_youtube_safe_text() -> None:
    """YouTube refuses a description holding angle brackets, and the notice
    is pasted as is, so curly quotes and the like become ASCII."""
    description = youtube_sidecar._format_description(
        [],
        lead=None,
        project_name="M",
        credits="Copyright © 2001\nTHIS SOFTWARE IS PROVIDED “AS IS” <here>",
    )
    head, credits = description.split("-- Generated by splitsmith (M)\n\n")
    assert credits == 'Copyright (c) 2001\nTHIS SOFTWARE IS PROVIDED "AS IS" here'


def test_an_export_drawn_with_the_look_carries_its_credits(
    user_looks: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    from typer.testing import CliRunner

    from splitsmith.cli import app

    from .test_match_cli_export import _capture_mp4, _seed

    _user_look(user_looks, credits="CREDITS.txt", text="Art from Somewhere, BSD licence.")
    root = _seed(tmp_path)
    _capture_mp4(monkeypatch)
    out = tmp_path / "out" / "lt.mp4"
    args = ["match", "export", str(root), "--shooter", "me", "--format", "mp4", "-o", str(out)]
    result = CliRunner().invoke(app, [*args, "--youtube-sidecar", "--theme", "mine"])
    assert result.exit_code == 0, result.output
    description = json.loads(out.with_name("lt-youtube.json").read_text())["description"]
    assert description.endswith("\n\nArt from Somewhere, BSD licence.")

    plain = CliRunner().invoke(app, [*args, "--youtube-sidecar"])
    assert plain.exit_code == 0, plain.output
    assert "Somewhere" not in json.loads(out.with_name("lt-youtube.json").read_text())["description"]


def test_the_grid_sidecar_closes_with_the_credits_too() -> None:
    sidecar = youtube_sidecar.build_grid_sidecar(match_name="M", chapters=[], credits="Art from Somewhere.")
    assert sidecar.description.endswith("\n\nArt from Somewhere.")
    assert "Somewhere" not in youtube_sidecar.build_grid_sidecar(match_name="M", chapters=[]).description
